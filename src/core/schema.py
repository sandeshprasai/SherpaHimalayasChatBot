from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional

# --- Intents and Strategies ---
class QueryIntent(Enum):
    LOOKUP    = "lookup"
    AGGREGATE = "aggregate"
    FILTER    = "filter"
    COMPARE   = "compare"
    SUMMARIZE = "summarize"
    GENERAL   = "general"

class RetrievalStrategy(Enum):
    VECTOR   = "vector"
    METADATA = "metadata"
    HYBRID   = "hybrid"
    FULL_DOC = "full_doc"

# --- The "Conductor" object that carries data through the pipeline ---
@dataclass
class QueryRequest:
    text: str
    normalized: str = ""
    # The 'data_plan' is generated by the Universal Classifier
    data_plan: Dict[str, Any] = field(default_factory=dict) 
    entities: List[Any] = field(default_factory=list)
    needs_entity: bool = False
    
    # Backward compatibility fields
    intent: Optional[QueryIntent] = None
    strategy: Optional[RetrievalStrategy] = None

    def __post_init__(self):
        if not self.normalized:
            self.normalized = self.text

# --- The Router's decision object ---
@dataclass
class RoutingDecision:
    strategy:         RetrievalStrategy
    use_metadata:     bool = False
    use_full_doc:     bool = False
    use_vector:       bool = True
    metadata_only:    bool = False
    reason:           str  = ""

# --- The Retrieval object (The missing piece!) ---
@dataclass
class SourceNode:
    text:       str
    score:      Optional[float] = None
    source_id:  Optional[str] = None
    title:      Optional[str] = None

# --- The Final Output object ---
@dataclass
class QueryResponse:
    answer:    str
    intent:    Optional[QueryIntent] = None
    strategy:  Optional[RetrievalStrategy] = None
    sources:   List[SourceNode] = field(default_factory=list)
    tokens_used: int = 0
    cost_usd:    float = 0.0
    used_llm:  bool = True
    is_fallback: bool = False