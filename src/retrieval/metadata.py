# --- src/retrieval/metadata.py ---
import os, json
from config.settings import settings
from core.schema import QueryRequest, QueryIntent

class MetadataRetriever:
    def __init__(self):
        meta_path = settings.cleaned_metadata_index if os.path.exists(settings.cleaned_metadata_index) else settings.metadata_index
        with open(meta_path, "r", encoding="utf-8") as f:
            all_data = json.load(f)
        
        # Guard: Only index actual products
        self._records = [
            r for r in all_data 
            if str(r.get("category", "")).lower() in ["trek", "expedition", "peak", "tour"]
            and str(r.get("type", "")).lower() not in ["team", "company", "blog"]
        ]

    def execute_plan(self, plan: dict) -> list[dict]:
        """
        Dynamically filters and sorts based on the plan generated by the LLM.
        """
        results = self._records
        
        # 1. Dynamic Filtering
        filters = plan.get("filters", {})
        if isinstance(filters, dict):
            for key, val in filters.items():
                if val:
                    results = [r for r in results if str(val).lower() in str(r.get(key, "")).lower()]

        # 2. Dynamic Mathematical Sorting
        if sort_cfg := plan.get("sort"):
            key = sort_cfg.get("field")
            if key:
                # Only sort records that have numeric values for the requested field
                candidates = [r for r in results if isinstance(r.get(key), (int, float))]
                if candidates:
                    results = sorted(candidates, key=lambda x: x[key], 
                                     reverse=(sort_cfg.get("direction") == "desc"))

        limit = plan.get("limit", 5)
        return results[:limit]